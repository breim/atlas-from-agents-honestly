BUCKETS = ("production", "adversarial", "constructed", "replay")


def _kappa_bps(cases: list) -> int:
    """Two annotators on the same guidance should agree; below the floor it is noise."""
    both = [c for c in cases if len(c["labels"]) == 2]
    if not both:
        return 10000
    agreed = len([c for c in both if c["labels"][0] == c["labels"][1]])
    return int(agreed * 10000 / len(both) + 0.5)


def assess(cases: list, policy: dict) -> dict:
    routes = sorted({c["route"] for c in cases})
    reports = []

    for route in routes:
        mine = [c for c in cases if c["route"] == route]
        errors = []
        warnings = []

        buckets = {b: len([c for c in mine if c["bucket"] == b]) for b in BUCKETS}
        for bucket in policy["requiredBuckets"]:
            if buckets[bucket] == 0:
                errors.append(f"{route} has no {bucket} cases")

        # Never generate eval data with the model family you are evaluating.
        incestuous = [c for c in mine if c["generatedBy"] == policy["evaluatedFamily"]]
        if incestuous:
            errors.append(
                f"{route} has {len(incestuous)} cases generated by the family under test"
            )

        # Harvest the centre, synthesise the edges — the opposite of the instinct.
        synthetic_production = [
            c for c in mine if c["bucket"] == "production" and c["origin"] == "synthetic"
        ]
        if synthetic_production:
            errors.append(
                f"{route} synthesises its production bucket, which collapses to modal phrasing"
            )

        kappa = _kappa_bps(mine)
        if kappa < policy["minKappaBps"]:
            errors.append(
                f"{route} agrees at {kappa} bps, which is a spec bug rather than an "
                "annotator problem"
            )

        # A set harvested from production is a second copy of customer data.
        leaking = [c for c in mine if c["containsPii"] and not c["redacted"]]
        if leaking:
            errors.append(f"{route} holds {len(leaking)} unredacted cases")

        # When production failures stop appearing, coverage has decayed.
        fresh = [
            c
            for c in mine
            if c["bucket"] == "production"
            and c["ageDays"] <= policy["productionFreshnessDays"]
        ]
        if buckets["production"] > 0 and not fresh:
            warnings.append(
                f"{route} has no production case newer than "
                f"{policy['productionFreshnessDays']} days"
            )

        # Past the ceiling, stratified sampling beats growing the set.
        sampled = len(mine) > policy["maxPerRoute"]
        size = policy["maxPerRoute"] if sampled else len(mine)
        if sampled:
            warnings.append(
                f"{route} is sampled down from {len(mine)} to {policy['maxPerRoute']}"
            )

        judge_calls = size * policy["rubricsPerCase"]
        if judge_calls > policy["judgeCallBudget"]:
            errors.append(
                f"{route} costs {judge_calls} judge calls against a budget of "
                f"{policy['judgeCallBudget']}"
            )

        reports.append(
            {
                "route": route,
                "size": size,
                "buckets": buckets,
                "kappaBps": kappa,
                "judgeCalls": judge_calls,
                "sampled": sampled,
                "errors": errors,
                "warnings": warnings,
            }
        )

    return {
        # One golden set per route: a blended score hides a collapse elsewhere.
        "status": "unusable" if any(r["errors"] for r in reports) else "usable",
        "routes": reports,
    }
