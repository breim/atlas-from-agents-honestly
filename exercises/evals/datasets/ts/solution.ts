export interface Case {
  id: string;
  route: string;
  bucket: 'production' | 'adversarial' | 'constructed' | 'replay';
  origin: 'harvested' | 'synthetic';
  generatedBy: string | null;
  labels: string[];
  containsPii: boolean;
  redacted: boolean;
  ageDays: number;
}

export interface Policy {
  maxPerRoute: number;
  requiredBuckets: string[];
  minKappaBps: number;
  evaluatedFamily: string;
  productionFreshnessDays: number;
  rubricsPerCase: number;
  judgeCallBudget: number;
}

export interface RouteReport {
  route: string;
  size: number;
  buckets: Record<string, number>;
  kappaBps: number;
  judgeCalls: number;
  sampled: boolean;
  errors: string[];
  warnings: string[];
}

export interface Report {
  status: 'usable' | 'unusable';
  routes: RouteReport[];
}

// Two annotators on the same guidance should agree. Below the floor the labels are noise.
function kappaBps(cases: Case[]): number {
  const both = cases.filter((item) => item.labels.length === 2);
  if (both.length === 0) return 10000;
  const agreed = both.filter((item) => item.labels[0] === item.labels[1]).length;
  return Math.floor((agreed * 10000) / both.length + 0.5);
}

export function assess(cases: Case[], policy: Policy): Report {
  const routes = [...new Set(cases.map((item) => item.route))].sort();

  const reports = routes.map((route) => {
    const mine = cases.filter((item) => item.route === route);
    const errors: string[] = [];
    const warnings: string[] = [];

    const buckets: Record<string, number> = {};
    for (const bucket of ['production', 'adversarial', 'constructed', 'replay']) {
      buckets[bucket] = mine.filter((item) => item.bucket === bucket).length;
    }
    for (const bucket of policy.requiredBuckets) {
      if (buckets[bucket] === 0) errors.push(`${route} has no ${bucket} cases`);
    }

    // Never generate eval data with the model family you are evaluating.
    const incestuous = mine.filter((item) => item.generatedBy === policy.evaluatedFamily);
    if (incestuous.length > 0) {
      errors.push(`${route} has ${incestuous.length} cases generated by the family under test`);
    }

    // Harvest the centre, synthesise the edges — which is the opposite of the instinct.
    const productionSynthetic = mine.filter((item) => item.bucket === 'production' && item.origin === 'synthetic');
    if (productionSynthetic.length > 0) {
      errors.push(`${route} synthesises its production bucket, which collapses to modal phrasing`);
    }

    const kappa = kappaBps(mine);
    if (kappa < policy.minKappaBps) {
      errors.push(`${route} agrees at ${kappa} bps, which is a spec bug rather than an annotator problem`);
    }

    // A set harvested from production is a second copy of customer data.
    const leaking = mine.filter((item) => item.containsPii && !item.redacted);
    if (leaking.length > 0) errors.push(`${route} holds ${leaking.length} unredacted cases`);

    // When production failures stop appearing, coverage has decayed.
    const fresh = mine.filter((item) => item.bucket === 'production' && item.ageDays <= policy.productionFreshnessDays);
    if (buckets.production > 0 && fresh.length === 0) {
      warnings.push(`${route} has no production case newer than ${policy.productionFreshnessDays} days`);
    }

    // Past the ceiling, stratified sampling beats growing the set.
    const sampled = mine.length > policy.maxPerRoute;
    const size = sampled ? policy.maxPerRoute : mine.length;
    if (sampled) warnings.push(`${route} is sampled down from ${mine.length} to ${policy.maxPerRoute}`);

    const judgeCalls = size * policy.rubricsPerCase;
    if (judgeCalls > policy.judgeCallBudget) {
      errors.push(`${route} costs ${judgeCalls} judge calls against a budget of ${policy.judgeCallBudget}`);
    }

    return { route, size, buckets, kappaBps: kappa, judgeCalls, sampled, errors, warnings };
  });

  return {
    // One golden set per route: a blended score hides a collapse behind stability elsewhere.
    status: reports.some((report) => report.errors.length > 0) ? 'unusable' : 'usable',
    routes: reports,
  };
}
