import assert from 'node:assert/strict';
import test from 'node:test';
import { expected, findCase, loadImpl } from '#harness';
import type { Case as EvalCase, Policy, Report, assess as AssessFn } from './start.ts';

interface Entry { id: string; cases: EvalCase[]; policy: Policy; result: Report }
interface Fixture { chapter: string; policy: Policy; cases: Entry[] }

const fixture = expected<Fixture>(import.meta.url);
const { assess } = await loadImpl<{ assess: typeof AssessFn }>(import.meta.url);
const go = (entry: Entry, cases = entry.cases, policy = entry.policy) => assess(cases, policy);

const cases: Array<[string, string]> = [
  ['a-set-with-all-four-buckets-is-usable', 'built on purpose'],
  ['one-golden-set-per-route-not-one-per-application', 'a blended score hides a collapse'],
  ['a-missing-bucket-makes-the-set-unusable', 'the replay bucket keeps it learning'],
  ['a-set-generated-by-the-family-under-test-is-refused', 'a suspicion about the set first'],
  ['synthesising-the-production-bucket-is-refused', 'harvest the centre'],
  ['annotators-who-disagree-are-a-spec-bug', 'no definition of success'],
  ['an-unredacted-case-is-a-second-copy-of-customer-data', 'a different lifetime'],
  ['a-stale-production-bucket-is-warned-about', 'coverage decays quietly'],
  ['past-the-ceiling-the-set-is-sampled-rather-than-grown', 'the constraint is judge cost'],
  ['a-rubric-count-that-blows-the-judge-budget-is-refused', 'sixty thousand calls per run'],
];

for (const [id, title] of cases) {
  test(title, () => {
    const entry = findCase<Entry>(fixture, id);
    assert.deepEqual(go(entry), entry.result);
  });
}

test('each route is judged on its own, never blended', () => {
  const entry = findCase<Entry>(fixture, 'one-golden-set-per-route-not-one-per-application');
  const outcome = go(entry);
  const routes = [...new Set(entry.cases.map((item) => item.route))];
  assert.equal(outcome.routes.length, routes.length, 'routes were merged');
  const healthy = findCase<Entry>(fixture, 'a-set-with-all-four-buckets-is-usable');
  const alone = go(healthy).routes[0];
  const together = outcome.routes.find((report) => report.route === alone.route)!;
  assert.deepEqual(together.buckets, alone.buckets, 'a route changed when another was added');
  assert.deepEqual(together.errors, alone.errors, 'a route inherited another route errors');
});

test('one bad route makes the whole set unusable', () => {
  for (const entry of fixture.cases) {
    const outcome = go(entry);
    const broken = outcome.routes.some((report) => report.errors.length > 0);
    assert.equal(outcome.status === 'unusable', broken, `${entry.id}: status disagrees with its routes`);
  }
});

test('every required bucket must be present, one missing at a time', () => {
  const entry = findCase<Entry>(fixture, 'a-set-with-all-four-buckets-is-usable');
  for (const bucket of entry.policy.requiredBuckets) {
    const stripped = entry.cases.filter((item) => item.bucket !== bucket);
    const outcome = go(entry, stripped);
    assert.equal(outcome.status, 'unusable', `a set with no ${bucket} bucket was accepted`);
    assert.ok(
      outcome.routes.some((report) => report.errors.some((error) => error.includes(bucket))),
      `the missing ${bucket} bucket was not named`,
    );
  }
});

test('nothing generated by the family under test is allowed anywhere', () => {
  const entry = findCase<Entry>(fixture, 'a-set-with-all-four-buckets-is-usable');
  for (const item of entry.cases) {
    const poisoned = entry.cases.map((candidate) =>
      candidate.id === item.id ? { ...candidate, generatedBy: entry.policy.evaluatedFamily } : candidate,
    );
    assert.equal(go(entry, poisoned).status, 'unusable', `${item.id} generated by the family was accepted`);
  }
});

test('the production bucket is harvested and the edges may be synthesised', () => {
  const entry = findCase<Entry>(fixture, 'a-set-with-all-four-buckets-is-usable');
  for (const bucket of ['production', 'adversarial', 'constructed', 'replay'] as const) {
    const flipped = entry.cases.map((item) =>
      item.bucket === bucket ? { ...item, origin: 'synthetic' as const, generatedBy: 'other-model' } : item,
    );
    const outcome = go(entry, flipped);
    assert.equal(outcome.status === 'unusable', bucket === 'production', `synthesising ${bucket}`);
  }
});

test('agreement is measured in basis points and floors the set', () => {
  const entry = findCase<Entry>(fixture, 'a-set-with-all-four-buckets-is-usable');
  const total = entry.cases.length;
  for (let agreeing = 0; agreeing <= total; agreeing += 1) {
    const labelled = entry.cases.map((item, index) => ({
      ...item,
      labels: index < agreeing ? ['ok', 'ok'] : ['ok', 'bad'],
    }));
    const report = go(entry, labelled).routes[0];
    assert.equal(report.kappaBps, Math.floor((agreeing * 10000) / total + 0.5), `${agreeing}/${total}`);
    assert.equal(
      report.errors.some((error) => error.includes('spec bug')),
      report.kappaBps < entry.policy.minKappaBps,
      `${agreeing}/${total} was judged wrongly`,
    );
  }
});

test('an unredacted case is refused wherever it sits', () => {
  const entry = findCase<Entry>(fixture, 'a-set-with-all-four-buckets-is-usable');
  for (const item of entry.cases) {
    const leaking = entry.cases.map((candidate) =>
      candidate.id === item.id ? { ...candidate, containsPii: true, redacted: false } : candidate,
    );
    assert.equal(go(entry, leaking).status, 'unusable', `${item.id} leaked and was accepted`);
    const redacted = entry.cases.map((candidate) =>
      candidate.id === item.id ? { ...candidate, containsPii: true, redacted: true } : candidate,
    );
    assert.equal(go(entry, redacted).status, 'usable', `${item.id} was refused after redaction`);
  }
});

test('staleness warns without making the set unusable', () => {
  const entry = findCase<Entry>(fixture, 'a-stale-production-bucket-is-warned-about');
  const outcome = go(entry);
  assert.equal(outcome.status, 'usable', 'a stale set was refused rather than flagged');
  assert.ok(
    outcome.routes.some((report) => report.warnings.some((warning) => warning.includes('newer than'))),
    'decayed coverage was not reported',
  );
});

test('sampling caps the size and the judge bill without dropping the route', () => {
  const entry = findCase<Entry>(fixture, 'past-the-ceiling-the-set-is-sampled-rather-than-grown');
  const report = go(entry).routes[0];
  assert.equal(report.sampled, true, 'the set was not sampled');
  assert.equal(report.size, entry.policy.maxPerRoute, 'the sample is the wrong size');
  assert.ok(entry.cases.length > report.size, 'the fixture no longer exceeds the ceiling');
  assert.ok(report.warnings.some((warning) => warning.includes('sampled down')), 'the sampling was silent');
});

test('the judge bill is the size times the rubrics, and it is a hard budget', () => {
  const entry = findCase<Entry>(fixture, 'a-set-with-all-four-buckets-is-usable');
  for (const rubrics of [1, 4, 8, 12]) {
    const outcome = go(entry, entry.cases, { ...entry.policy, rubricsPerCase: rubrics });
    const report = outcome.routes[0];
    assert.equal(report.judgeCalls, report.size * rubrics, `judge calls at ${rubrics} rubrics`);
    assert.equal(
      outcome.status === 'unusable',
      report.judgeCalls > entry.policy.judgeCallBudget,
      `${report.judgeCalls} against a budget of ${entry.policy.judgeCallBudget}`,
    );
  }
});

test('the bucket counts add up to the whole route', () => {
  for (const entry of fixture.cases) {
    for (const report of go(entry).routes) {
      const counted = Object.values(report.buckets).reduce((total, value) => total + value, 0);
      const mine = entry.cases.filter((item) => item.route === report.route).length;
      assert.equal(counted, mine, `${entry.id}: ${report.route} lost a case`);
      assert.ok(report.size <= mine, `${entry.id}: ${report.route} invented cases`);
    }
  }
});
